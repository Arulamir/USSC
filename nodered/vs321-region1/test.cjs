const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const collector=fs.readFileSync(path.join(__dirname,'VS321_Telemetry_region1.txt'),'utf8');
const display=fs.readFileSync(path.join(__dirname,'VS321_Debug_status_sensor.txt'),'utf8');
const eui='24E124443F431957';
let now=1800000000000;
const FakeDate=class extends Date{static now(){return now;}};
const flowMap=new Map(),contextMap=new Map();
const flow={get:k=>flowMap.get(k),set:(k,v)=>flowMap.set(k,v)};
const context={get:k=>contextMap.get(k),set:(k,v)=>contextMap.set(k,v)};
function processPacket(payload){
    const message={deveui:eui,payload};
    const execute=code=>new Function('msg','flow','context','Date',code)(message,flow,context,FakeDate);
    execute(collector);
    return execute(display);
}
const saved=()=>flow.get('telemetry_latest_v1')[eui];
flow.set('vs321_occupancy',{eui,value:'vacant',updatedAt:now});
let result=processPacket({region_1:'occupied',people_total_counts:0,occupancy:'vacant',illuminance_status:'dim'});
assert.equal(saved().occupancy.value,'occupied');
assert.equal(result.payload.occupancy,'occupied');
assert.equal(result.payload.illumination,'dim');
assert.equal(flow.get('vs321_occupancy').value,'vacant');
result=processPacket({region_1:'vacant',region_2:'occupied',people_total_counts:5,occupancy:'occupied'});
assert.equal(saved().occupancy.value,'vacant');
assert.equal(result.payload.occupancy,'vacant');
const originalOccAt=saved().occupancy.receivedAt,originalLightAt=saved().illumination.receivedAt;
now+=60000;
result=processPacket({temperature:26.5,people_total_counts:5,occupancy:'occupied'});
assert.equal(saved().occupancy.receivedAt,originalOccAt);
assert.equal(saved().illumination.receivedAt,originalLightAt);
assert.equal(result.payload.illumination_at,new Date(originalLightAt).toISOString());
assert.equal(result.payload.sensor_report.illuminance_status,null);
now+=16*60000;
assert.equal(processPacket({temperature:26.6}).payload.occupancy,null);
now+=15*60000;
assert.equal(processPacket({temperature:26.7}).payload.illumination,null);
processPacket({region_1:'unknown',illuminance_status:'unknown'});
assert.ok(!saved().occupancy);assert.ok(!saved().illumination);
flow.set('telemetry_latest_v1',{[eui]:{occupancy:{value:'vacant',receivedAt:now}}});
processPacket({people_total_counts:0,occupancy:'vacant'});
assert.ok(!saved().occupancy);
console.log('PASS: region_1 only; conflicting counts and other regions ignored; absent reports retain actual ages; stale and invalid become null; dim preserved; automation context unchanged.');
